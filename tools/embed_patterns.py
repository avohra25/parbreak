#!/usr/bin/env python3
"""Regenerate src/hyph_en_us.c from data/hyph-en-us.txt.

The built-in pattern set is embedded as an array of C strings (one per line,
keeping every literal well under the C99 minimum length limit) so the library and CLI
work without any data files. Run from the repository root:

    python3 tools/embed_patterns.py
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = (root / "data" / "hyph-en-us.txt").read_text(encoding="utf-8")
lines = []
for line in data.splitlines():
    if line.startswith("%"):
        lines.append("/* " + line[1:].strip().replace("*/", "* /") + " */")
        continue
    lines.append('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '",')

out = ["/* Generated by tools/embed_patterns.py from data/hyph-en-us.txt. Do not edit. */",
       "#include <stddef.h>", "",
       "const char *const pb_hyph_en_us_lines[] = {"]
body = [l for l in lines]
out.extend(body)
out.append("};")
out.append("const size_t pb_hyph_en_us_count = sizeof pb_hyph_en_us_lines / sizeof pb_hyph_en_us_lines[0];")
(root / "src" / "hyph_en_us.c").write_text("\n".join(out) + "\n", encoding="utf-8")
